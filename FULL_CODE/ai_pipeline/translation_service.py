"""Translation Service: Generates compliant Telugu care plans preserving Latin drug names and dates."""

from typing import Dict, List

class TranslationService:
    def __init__(self):
        pass

    def generate_telugu(self, cp: dict) -> str:
        out = ["నా సంరక్షణ ప్రణాళిక - చంద్రపురి జిల్లా ప్రభుత్వ ఆసుపత్రి"]
        out.append(
            "ఇంటి వద్ద మీ ఆరోగ్యం త్వరగా కుదుటపడటానికి మరియు సురక్షితంగా కోలుకోవడానికి ఈ క్రింది వైద్య సూచనలను క్రమం తప్పకుండా పాటించండి.\n"
        )

        out.append("మీరు తీసుకోవలసిన ముఖ్యమైన మందులు (వైద్యులు రాసిన ప్రకారం సమయానికి తీసుకోండి)")
        for i, m in enumerate(cp.get("medicines", []), 1):
            # Name and dose in Latin script with Western digits
            line = f"{i}. {m['name']} {m['dose']}"
            out.append(line)
            timing_te = (
                "భోజనం తర్వాత"
                if "after" in m.get("timing", "")
                else "భోజనానికి ముందు"
                if "before" in m.get("timing", "")
                else "సమయానికి"
            )
            freq_te = (
                "రోజుకు ఒకసారి"
                if "OD" in m.get("frequency", "")
                else "రోజుకు రెండు సార్లు"
                if "BD" in m.get("frequency", "")
                else "రోజుకు మూడు సార్లు"
                if "TDS" in m.get("frequency", "")
                else "అవసరమైనప్పుడు మాత్రమే"
                if "SOS" in m.get("frequency", "")
                else "క్రమంగా"
            )
            out.append(f"   - ఈ మందును {timing_te} {freq_te} కొద్దిగా నీటితో వేసుకోండి.")
            out.append("   - వైద్యులు సూచించిన గడువు వరకు రోజుకు తప్పకుండా క్రమం తప్పకుండా వాడండి.")

        if cp.get("stop_medicines"):
            out.append("\nతక్షణమే ఆపివేయవలసిన మందులు")
            for s in cp["stop_medicines"]:
                out.append(f"- STOP {s}. ఈ మందును ఇకపై అస్సలు వాడవద్దు. దీనిని వెంటనే నిలిపివేయండి.")

        out.append("\nఈ క్రింది ప్రమాదకర లక్షణాలు కనిపిస్తే ఆలస్యం చేయకుండా వెంటనే ఆసుపత్రికి రండి")
        out.append("- తీవ్రమైన తలనొప్పి, కంటి చూపు మందగించడం లేదా కడుపులో భరించలేని నొప్పి రావడం.")
        out.append("- తీవ్రమైన జ్వరం రావడం, ఒణుకు లేదా శరీరంలో ఫిట్స్ లేదా స్పృహ తప్పిపోవడం.")
        out.append("- శ్వాస తీసుకోవడంలో తీవ్రమైన ఇబ్బంది మరియు ఆయాసం కలగడం.")
        out.append("- గాయం వద్ద విపరీతమైన వాపు, ఎరుపుదనం లేదా చీము కారడం వంటివి కనిపించడం.")
        out.append("- రక్తపోటు లేదా షుగర్ స్థాయిలు ప్రమాదకర స్థాయికి పెరగడం లేదా తగ్గడం.")

        out.append("\nఆహారం మరియు జీవనశైలి జాగ్రత్తలు")
        out.append("- తేలికగా జీర్ణమయ్యే బలవర్ధకమైన తాజా పౌష్టికాహారం మరియు పండ్లు తీసుకోండి.")
        out.append("- ఉప్పు మరియు నూనె అధికంగా ఉండే పదార్థాలను, పచ్చళ్లను పూర్తిగా పరిమితం చేయండి.")
        out.append("- శరీరానికి సరిపడా శుభ్రమైన కాచి చల్లార్చిన మంచి నీటిని పుష్కలంగా త్రాగాలి.")

        out.append("\nవిశ్రాంతి మరియు శారీరక జాగ్రత్తలు")
        out.append("- తగినంత సమయం నిద్రపోతూ శరీరాన్ని ఎక్కువగా శ్రమపెట్టకుండా ప్రశాంతంగా విశ్రాంతి తీసుకోండి.")
        out.append("- బరువైన పనులను చేయకూడదు మరియు ఇంటి లోపల నెమ్మదిగా కొద్ది దూరం నడవండి.")

        if cp.get("follow_ups"):
            out.append("\nతదుపరి వైద్య పరీక్షల కోసం ఆసుపత్రికి తిరిగి రావలసిన ముఖ్యమైన తేదీలు")
            for f in cp["follow_ups"]:
                out.append(f"- {f['date']}: వైద్యులను కలిసి పరీక్ష చేయించుకోవడానికి అవసరమైన అన్ని పాత రిపోర్టులతో రండి.")

        out.append(
            "\nఏదైనా అత్యవసర సమయాల్లో చంద్రపురి జిల్లా ఆసుపత్రి అత్యవసర చికిత్స విభాగాన్ని (క్యాజువాలిటీ - 24 గంటలు అందుబాటులో ఉంటుంది) సంప్రదించండి."
        )
        out.append("మీ మందుల వాడకంలో ఏదైనా సందేహం ఉంటే లేదా మందు మార్చవలసి వస్తే ముందుగా మీ వైద్యుడిని లేదా నర్సును తప్పక అడగండి.")

        return "\n".join(out)
